import { join } from 'node:path';
import type { Rule } from '@orgspec/constitution';
import { type AgentDef, type Persona, writeFileAtomic } from '@orgspec/core';
import { stringify as toYaml } from 'yaml';
import { BUILTIN_PROMPTS } from './prompts.js';

const frontmatter = (data: Record<string, unknown>, body: string): string =>
  `---\n${toYaml(data, { lineWidth: 0 }).trimEnd()}\n---\n\n${body.trim()}\n`;

/** One `.claude/agents/<id>.md` file. */
export function renderAgent(def: AgentDef, extra: { mcpTools?: string[] } = {}): string {
  const builtin = BUILTIN_PROMPTS[def.id];
  const tools = def.tools ?? builtin?.tools;
  const allTools = tools ? [...tools, ...(extra.mcpTools ?? [])] : undefined;
  const data: Record<string, unknown> = {
    name: def.id,
    description: def.description || builtin?.description || def.id,
    model: def.model || builtin?.model || 'sonnet',
  };
  if (allTools) data.tools = allTools.join(', ');
  if (def.disallowedTools.length) data.disallowedTools = def.disallowedTools.join(', ');
  if (def.skills.length) data.skills = def.skills;
  if (def.permissionMode) data.permissionMode = def.permissionMode;
  return frontmatter(data, def.prompt ?? builtin?.body ?? `You are the ${def.id} agent.`);
}

/** The built-in agents every OrgSpec folder has, plus the persona's own. */
export function agentsFor(persona: Persona | undefined): AgentDef[] {
  const defaults: AgentDef[] = Object.keys(BUILTIN_PROMPTS).map((id) => ({
    id,
    description: '',
    model: '',
    skills: [],
    disallowedTools: [],
  }));
  const own = persona?.spec.agents ?? [];
  const byId = new Map<string, AgentDef>(defaults.map((a) => [a.id, a]));
  for (const a of own) byId.set(a.id, a);
  return [...byId.values()];
}

/** MCP tool names (`mcp__orgspec__jira__get_issue`) a persona grants, as Claude Code sees them through the gateway. */
export const grantedMcpTools = (persona: Persona | undefined): string[] =>
  (persona?.spec.mcp ?? []).flatMap((g) => g.tools.map((t) => `mcp__orgspec__${g.server}__${t}`));

/**
 * `.claude/rules/*.md`: unscoped rules in one file, path-scoped rules grouped by their path set so
 * Claude Code loads them only when it touches matching files.
 */
export function renderClaudeRules(
  rules: readonly Rule[],
  meta: { persona: string; version: string },
): Record<string, string> {
  const files: Record<string, string> = {};
  const line = (r: Rule) =>
    `- **${r.title}** (\`${r.id}\`${r.enforcement === 'advisory' ? '' : `, enforced in ${r.enforcement}`}): ${r.statement}`;
  const header = `Generated by OrgSpec from constitution ${meta.persona} ${meta.version}. Do not edit; changes are overwritten.`;
  const unscoped = rules.filter((r) => r.appliesTo.paths.length === 0);
  files['orgspec-constitution.md'] = `# Constitution\n\n${header}\n\n${unscoped.map(line).join('\n')}\n`;

  const groups = new Map<string, Rule[]>();
  for (const r of rules) {
    if (!r.appliesTo.paths.length) continue;
    const key = [...r.appliesTo.paths].sort().join('|');
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  let n = 0;
  for (const [key, list] of groups) {
    n++;
    const slug = (list[0]?.id ?? `group-${n}`).replace(/\./g, '-');
    files[`orgspec-${slug}.md`] = frontmatter(
      { paths: key.split('|') },
      `# Rules for these paths\n\n${header}\n\n${list.map(line).join('\n')}`,
    );
  }
  return files;
}

export interface ClaudeFolderOptions {
  /** Folder Claude Code runs in (a ticket folder or a repo checkout). */
  dir: string;
  persona?: Persona;
  rules: readonly Rule[];
  bundle: { persona: string; version: string };
  /** Session ID the gateway uses to scope tools and audit entries. */
  sessionId: string;
  orgspecBin?: string;
}

/**
 * Writes `.claude/agents`, `.claude/rules` and `.mcp.json` into a folder. Agent files are written per
 * folder because plugin subagents ignore `mcpServers` and `hooks`.
 */
export function writeClaudeFolder(o: ClaudeFolderOptions): string[] {
  const written: string[] = [];
  const put = (rel: string, text: string) => {
    writeFileAtomic(join(o.dir, rel), text);
    written.push(rel);
  };
  const mcpTools = grantedMcpTools(o.persona);
  for (const a of agentsFor(o.persona)) put(`.claude/agents/${a.id}.md`, renderAgent(a, { mcpTools }));
  for (const [f, text] of Object.entries(renderClaudeRules(o.rules, o.bundle))) put(`.claude/rules/${f}`, text);
  put('.mcp.json', `${JSON.stringify(mcpConfig(o.sessionId, o.orgspecBin), null, 2)}\n`);
  put('.claude/settings.json', `${JSON.stringify(projectSettings(o.orgspecBin), null, 2)}\n`);
  return written;
}

export const mcpConfig = (sessionId: string, bin = 'orgspec') => ({
  mcpServers: { orgspec: { command: bin, args: ['gateway', '--stdio', '--session', sessionId] } },
});

/** Paths Claude Code reads managed (admin) settings from. */
export function managedSettingsPath(platform: NodeJS.Platform = process.platform): string {
  if (platform === 'darwin') return '/Library/Application Support/ClaudeCode/managed-settings.json';
  if (platform === 'win32') return 'C:\\Program Files\\ClaudeCode\\managed-settings.json';
  return '/etc/claude-code/managed-settings.json';
}

/**
 * Managed settings IT installs on every machine: only OrgSpec's hooks and gateway may run,
 * marketplaces are pinned, and dangerous commands are denied.
 */
export function renderManagedSettings(
  opts: { orgspecBin?: string; marketplaces?: string[]; extraDeny?: string[] } = {},
) {
  const bin = opts.orgspecBin ?? 'orgspec';
  const exe = /\s/.test(bin) ? `'${bin.replace(/'/g, `'\\''`)}'` : bin;
  const hook = (args: string, timeout = 5) => [{ type: 'command', command: `${exe} hook ${args}`, timeout }];
  return {
    allowManagedHooksOnly: true,
    allowManagedMcpServersOnly: true,
    allowedMcpServers: [{ serverName: 'orgspec' }],
    strictKnownMarketplaces: opts.marketplaces ?? [],
    permissions: {
      deny: [
        'Bash(git push --force:*)',
        'Bash(git push -f:*)',
        'Bash(gh auth token:*)',
        'Bash(gh repo delete:*)',
        'Bash(curl:*)',
        'Bash(wget:*)',
        'Read(~/.ssh/**)',
        'Read(~/.config/gh/**)',
        'Read(**/.env)',
        ...(opts.extraDeny ?? []),
      ],
      disableBypassPermissionsMode: 'disable',
    },
    hooks: {
      PreToolUse: [{ matcher: 'Bash|Edit|Write|MultiEdit|NotebookEdit', hooks: hook('pre-tool-use') }],
      PreCompact: [{ hooks: hook('checkpoint --reason compact', 15) }],
      SessionStart: [{ matcher: 'compact|resume', hooks: hook('restore', 10) }],
      Stop: [{ hooks: hook('checkpoint --reason stop', 15) }],
      SessionEnd: [{ hooks: hook('session-end', 15) }],
    },
  };
}

/**
 * Project settings for a ticket folder: the same hooks and deny rules as the managed settings, so
 * enforcement works before IT installs them. Under `allowManagedHooksOnly` Claude Code ignores these
 * hooks and runs only the managed copy, so nothing runs twice.
 */
export function projectSettings(orgspecBin = 'orgspec') {
  const m = renderManagedSettings({ orgspecBin });
  return {
    hooks: m.hooks,
    permissions: { deny: m.permissions.deny },
    enabledMcpjsonServers: ['orgspec'],
    enableAllProjectMcpServers: false,
  };
}

/** The command that runs this OrgSpec: `ORGSPEC_SELF`, the single executable itself, or `orgspec` on PATH. */
export function selfCommand(env: NodeJS.ProcessEnv = process.env): string {
  if (env.ORGSPEC_SELF) return env.ORGSPEC_SELF;
  const exe = process.execPath;
  return /(^|\/)orgspec(\.exe)?$/.test(exe) ? exe : 'orgspec';
}
